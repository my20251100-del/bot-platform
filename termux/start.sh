#!/data/data/com.termux/files/usr/bin/bash
# ========================================================
#   تشغيل محرك البوت تلقائياً على Termux في الخلفية 24/7
# ========================================================

# 1. منع الأندرويد من إيقاف المعالج عند قفل الشاشة
termux-wake-lock 2>/dev/null || true

echo "========================================================"
echo "  🚀 بدء تشغيل محرك واتساب في Termux (شغال 24 ساعة)"
echo "========================================================"

# الانتقال لمجلد السكربت
cd "$(dirname "$0")"

# التحقق من تثبيت الحزم
if [ ! -d "node_modules" ]; then
    echo "==> تثبيت الحزم المطلوبة لأول مرة..."
    npm install --omit=dev
fi

# حلقة تكرار لضمان إعادة التشغيل التلقائي إذا انقطع النت
while true; do
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] جاري تشغيل المحرك..."
    ENV_ARG=""
    if [ -f ".env.local" ]; then
        ENV_ARG="--env-file=.env.local"
    elif [ -f ".env" ]; then
        ENV_ARG="--env-file=.env"
    fi
    node $ENV_ARG engine/index.mjs
    echo "[$(date '+%Y-%m-%d %H:%M:%S')] تم إيقاف المحرك، إعادة التشغيل بعد 3 ثواني..."
    sleep 3
done
